CREATE TABLE IF NOT EXISTS public.employee_stock_reports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id INTEGER REFERENCES public.products(id) ON DELETE SET NULL,
  employee_id UUID REFERENCES public.users(id) ON DELETE SET NULL,
  reported_quantity INTEGER NOT NULL CHECK (reported_quantity >= 0),
  note TEXT NOT NULL CHECK (char_length(note) BETWEEN 1 AND 500),
  status TEXT NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'approved', 'rejected')),
  reviewed_by UUID REFERENCES public.users(id) ON DELETE SET NULL,
  submitted_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  reviewed_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS employee_stock_reports_status_submitted_at_idx
  ON public.employee_stock_reports (status, submitted_at);

CREATE INDEX IF NOT EXISTS employee_stock_reports_employee_submitted_at_idx
  ON public.employee_stock_reports (employee_id, submitted_at DESC);
