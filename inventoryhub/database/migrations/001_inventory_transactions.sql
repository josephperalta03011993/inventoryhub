CREATE TABLE IF NOT EXISTS public.inventory_transactions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id INTEGER REFERENCES public.products(id) ON DELETE SET NULL,
  user_id UUID REFERENCES public.users(id) ON DELETE SET NULL,
  transaction_type TEXT NOT NULL
    CHECK (transaction_type IN ('stock_adjustment', 'restock', 'physical_count')),
  previous_quantity INTEGER NOT NULL,
  new_quantity INTEGER NOT NULL,
  quantity_change INTEGER NOT NULL,
  reason TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS inventory_transactions_created_at_idx
  ON public.inventory_transactions (created_at DESC);

CREATE INDEX IF NOT EXISTS inventory_transactions_user_id_idx
  ON public.inventory_transactions (user_id);

INSERT INTO public.inventory_transactions (
  product_id,
  transaction_type,
  previous_quantity,
  new_quantity,
  quantity_change,
  reason
)
SELECT
  product.id,
  'physical_count',
  0,
  product.stock,
  product.stock,
  'Opening balance at transaction history setup'
FROM public.products AS product
WHERE NOT EXISTS (
  SELECT 1
  FROM public.inventory_transactions AS tx
  WHERE tx.product_id = product.id
    AND tx.reason = 'Opening balance at transaction history setup'
);
